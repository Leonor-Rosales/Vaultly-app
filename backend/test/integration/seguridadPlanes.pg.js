const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { Pool } = require('pg');
const { migrar } = require('../../src/infrastructure/migraciones');
const { crearAdminRepositorio } = require('../../src/infrastructure/adminRepositorio');
const { crearCasosAdministracion } = require('../../src/usecases/administracion');
const { crearPagosRepositorio } = require('../../src/infrastructure/pagosRepositorio');
const { crearCasosPagos } = require('../../src/usecases/pagos');

test('seguridad de planes: concurrencia, versiones de compra, auditoría atómica y precio cero', async t => {
  const url = new URL(process.env.TEST_MIGRATIONS_DATABASE_URL || 'http://invalid');
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.pathname === '/vaultly_migraciones_test');
  const db = new Pool({ connectionString: url.toString() });
  const schema = 'seguridad_' + randomUUID().replaceAll('-', '');
  await db.query(`CREATE SCHEMA ${schema}`);
  const pool = new Pool({ connectionString: url.toString(), options: `-c search_path=${schema},public` });
  t.after(async () => { await pool.end(); await db.query(`DROP SCHEMA ${schema} CASCADE`); await db.end(); });
  await migrar(pool, () => {}); await migrar(pool, () => {});
  const actor = randomUUID(), cliente = randomUUID();
  await pool.query("INSERT INTO usuarios(id,rol_id,nombre_completo,correo_electronico,password_hash) VALUES($1,1,'Admin','admin@example.test','fixture'),($2,2,'Cliente','cliente@example.test','fixture')", [actor, cliente]);
  const repo = crearAdminRepositorio(pool);
  const admin = crearCasosAdministracion({ repo });
  const datos = { nombre: 'Prueba segura', precio_mensual: 49, cuota_storage_gb: 50, limite_descargas: null, activo: true, permite_carpetas_publicas: false };
  const contar = async tabla => Number((await pool.query(`SELECT count(*) AS n FROM ${tabla}`)).rows[0].n);
  await assert.rejects(admin.guardarPlan(cliente, null, datos), { estado: 403 });
  await assert.rejects(admin.guardarPlan(actor, null, { ...datos, precio_mensual: 0 }), { codigo: 'PRECIO_CERO_NO_PERMITIDO' });
  assert.equal(await contar('auditoria'), 0);
  const creado = await admin.guardarPlan(actor, null, datos);
  const cambios = await Promise.allSettled([79, 99].map(precio_mensual => admin.guardarPlan(actor, creado.id, { ...datos, version: creado.version, precio_mensual })));
  assert.equal(cambios.filter(r => r.status === 'fulfilled').length, 1);
  assert.equal(cambios.find(r => r.status === 'rejected').reason.codigo, 'PLAN_DESACTUALIZADO');
  const actual = (await repo.listarPlanes()).find(p => p.id === creado.id);
  assert.equal(actual.version, creado.version + 1);
  const pagos = crearCasosPagos({ repo: crearPagosRepositorio(pool) });
  const suscripcionesAntes = (await pool.query('SELECT * FROM suscripciones ORDER BY id')).rows;
  for (const versionPlan of [undefined, creado.version, 999]) await assert.rejects(async () => pagos.contratar(cliente, { planId: creado.id, metodo: 'tarjeta', versionPlan }), { codigo: 'PLAN_DESACTUALIZADO' });
  assert.equal(await contar('pagos'), 0);
  assert.deepEqual((await pool.query('SELECT * FROM suscripciones ORDER BY id')).rows, suscripcionesAntes);
  const compra = await pagos.contratar(cliente, { planId: creado.id, metodo: 'tarjeta', versionPlan: actual.version, monto: 0, precio_mensual: 0 });
  assert.equal(compra.monto, Number(actual.precio_mensual));
  await assert.rejects(admin.guardarPlan(actor, creado.id, { ...actual, precio_mensual: 150 }), /suscripciones/);
  const retirado = await admin.guardarPlan(actor, creado.id, { ...actual, precio_mensual: Number(actual.precio_mensual), activo: false });
  await admin.guardarPlan(actor, creado.id, { ...retirado, precio_mensual: Number(retirado.precio_mensual), activo: true });
  const { rows: auditoria } = await pool.query("SELECT a.*,t.codigo FROM auditoria a JOIN tipos_accion t ON t.id=a.tipo_accion_id ORDER BY a.id");
  assert.deepEqual(auditoria.map(a => a.codigo), ['PLAN_CREADO','PLAN_EDITADO','PLAN_DESACTIVADO','PLAN_ACTIVADO']);
  assert.ok(auditoria.every(a => a.usuario_id === actor && a.modulo_afectado === 'planes' && a.fecha_hora));
  assert.equal(auditoria[0].detalles_json.anterior, null);
  assert.equal(Number(auditoria[1].detalles_json.anterior.precio_mensual), 49);
  assert.equal(Number(auditoria[1].detalles_json.nuevo.precio_mensual), Number(actual.precio_mensual));
  // Un fallo en auditoría debe revertir tanto el plan como su versión.
  const otro = await admin.guardarPlan(actor, null, { ...datos, nombre: 'Rollback' });
  const roto = crearCasosAdministracion({ repo: { transaccion: (tipo, fn) => repo.transaccion(tipo, tx => fn({ ...tx, auditarPlan: async () => { throw Error('fallo auditoría'); } })) } });
  await assert.rejects(roto.guardarPlan(actor, otro.id, { ...otro, precio_mensual: 99 }), /fallo auditoría/);
  assert.deepEqual((await repo.listarPlanes()).find(p => p.id === otro.id), otro.suscripciones_vigentes === undefined ? { ...otro, suscripciones_vigentes: 0 } : otro);
  const { rows: [directo] } = await pool.query('UPDATE planes SET precio_mensual=79 WHERE id=$1 RETURNING version', [otro.id]);
  assert.equal(directo.version, otro.version + 1);
});
