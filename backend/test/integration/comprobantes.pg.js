const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { Pool } = require('pg');
const { listarMigraciones, migrar } = require('../../src/infrastructure/migraciones');
const { crearPagosRepositorio } = require('../../src/infrastructure/pagosRepositorio');
const { crearCuotasRepositorio } = require('../../src/infrastructure/cuotasRepositorio');
const { crearCasosPagos } = require('../../src/usecases/pagos');
const { crearCasosCuotas } = require('../../src/usecases/cuotas');

test('PostgreSQL: migra sin inventar datos antiguos y conserva compras y renovaciones', async t => {
  const url = new URL(process.env.TEST_MIGRATIONS_DATABASE_URL || 'http://invalid');
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.pathname === '/vaultly_migraciones_test');
  const admin = new Pool({ connectionString: url.toString() });
  const schema = 'comprobante_' + randomUUID().replaceAll('-', '');
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool = new Pool({ connectionString: url.toString(), options: `-c search_path=${schema},public` });
  t.after(async () => { await pool.end(); await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.end(); });
  for (const m of listarMigraciones().filter(m => m.numero < 12)) await pool.query(m.sql);
  const usuario = randomUUID();
  await pool.query("INSERT INTO usuarios(id,rol_id,nombre_completo,correo_electronico,password_hash) VALUES($1,2,'Ana original','original@example.test','fixture')", [usuario]);
  const { rows: [plan] } = await pool.query("INSERT INTO planes(nombre,precio_mensual,cuota_storage_gb,limite_descargas) VALUES('Comprobante',49,50,NULL) RETURNING *");
  const viejo = randomUUID();
  await pool.query("INSERT INTO pagos(id,usuario_id,plan_id,plan_nombre,monto,metodo,codigo) VALUES($1,$2,$3,'Plan histórico',15,'TARJETA','ANTIGUO')", [viejo, usuario, plan.id]);
  await migrar(pool, () => {});
  await migrar(pool, () => {});
  const casos = crearCasosPagos({ repo: crearPagosRepositorio(pool) });
  assert.equal((await casos.historial(usuario))[0].comprobante, null);
  const compra = await casos.contratar(usuario, { planId: plan.id, versionPlan: 1, metodo: 'tarjeta', renovar: true });
  const { rows: [suscripcion] } = await pool.query("SELECT * FROM suscripciones WHERE usuario_id=$1 AND estado='ACTIVA'", [usuario]);
  assert.equal(compra.comprobante.inicio, suscripcion.fecha_inicio.toISOString());
  assert.equal(compra.comprobante.fin, suscripcion.fecha_fin.toISOString());
  await pool.query("UPDATE usuarios SET nombre_completo='Ana nueva',correo_electronico='nueva@example.test' WHERE id=$1", [usuario]);
  await pool.query("UPDATE planes SET cuota_storage_gb=70,limite_descargas=5,nombre='Plan editado' WHERE id=$1", [plan.id]);
  assert.deepEqual((await casos.historial(usuario)).find(p => p.id === compra.id), compra);
  // El siguiente pago por renovación conserva los datos vigentes en esa renovación.
  const repo = crearCuotasRepositorio(pool);
  const futuro = new Date(+suscripcion.fecha_fin + 1000);
  const reloj = { ...repo, conUsuario: (id, fn) => repo.conUsuario(id, tx => { tx.ahora = futuro; return fn(tx); }) };
  await crearCasosCuotas({ repo: reloj, almacenamiento: {} }).consultar(usuario);
  const pagos = await casos.historial(usuario);
  assert.equal(pagos.length, 3);
  const renovado = pagos.find(p => p.id !== compra.id && p.id !== viejo);
  assert.equal(renovado.comprobante.cliente.nombre, 'Ana nueva');
  assert.equal(renovado.comprobante.almacenamientoGb, 70);
  assert.equal(renovado.comprobante.descargasMensuales, 5);
  assert.equal(renovado.comprobante.inicio, futuro.toISOString());
  assert.equal(renovado.monto, 49);
  assert.deepEqual(pagos.find(p => p.id === compra.id), compra);
});
