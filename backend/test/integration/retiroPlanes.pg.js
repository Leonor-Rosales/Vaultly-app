const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { Pool } = require('pg');
const { listarMigraciones, migrar } = require('../../src/infrastructure/migraciones');
const { limpiarPlanesInactivos } = require('../../src/infrastructure/limpiezaPlanes');
const { crearAdminRepositorio } = require('../../src/infrastructure/adminRepositorio');
const { crearCasosAdministracion } = require('../../src/usecases/administracion');
const { crearCasosPagos } = require('../../src/usecases/pagos');
const { crearPagosRepositorio } = require('../../src/infrastructure/pagosRepositorio');
const { crearCuotasRepositorio } = require('../../src/infrastructure/cuotasRepositorio');
const { crearCasosCuotas } = require('../../src/usecases/cuotas');

test('retiro de planes: 30 días, historial, suscripciones, reactivación, concurrencia y auditoría atómica', async t => {
  const url = new URL(process.env.TEST_MIGRATIONS_DATABASE_URL || 'http://invalid');
  assert.ok(['127.0.0.1','localhost'].includes(url.hostname) && url.pathname === '/vaultly_migraciones_test');
  const db = new Pool({ connectionString: url.toString() });
  const schema = 'retiro_' + randomUUID().replaceAll('-', ''); await db.query(`CREATE SCHEMA ${schema}`);
  const pool = new Pool({ connectionString: url.toString(), options: `-c search_path=${schema},public` });
  t.after(async () => { await pool.end(); await db.query(`DROP SCHEMA ${schema} CASCADE`); await db.end(); });
  for (const m of listarMigraciones().filter(m => m.numero <= 15)) await pool.query(m.sql);
  const { rows: [previo] } = await pool.query("INSERT INTO planes(nombre,precio_mensual,cuota_storage_gb,activo) VALUES('Inactivo previo',20,10,false) RETURNING *");
  await migrar(pool, () => {}); await migrar(pool, () => {});
  const { rows: [{ ahora: instante }] } = await pool.query('SELECT clock_timestamp() AS ahora');
  let ahora = instante;
  const dia = 86400000;
  const reloj = (fallarAuditoria = false) => ({ connect: async () => {
    const c = await pool.connect();
    return { release: () => c.release(), query: (sql, args) => {
      if (sql === 'SELECT clock_timestamp() AS ahora') return Promise.resolve({ rows: [{ ahora }] });
      if (fallarAuditoria && sql.includes('INSERT INTO auditoria')) return Promise.reject(Error('fallo auditoría de prueba'));
      return c.query(sql, args);
    } };
  } });
  const actor = randomUUID(), usuarios = [randomUUID(), randomUUID(), randomUUID()];
  for (const [i,id] of [actor,...usuarios].entries()) await pool.query("INSERT INTO usuarios(id,rol_id,nombre_completo,correo_electronico,password_hash) VALUES($1,$2,$3,$4,'fixture')", [id, i===0?1:2, `Prueba ${i}`, `${id}@example.test`]);
  const crear = async (nombre, edad) => {
    const { rows: [plan] } = await pool.query('INSERT INTO planes(nombre,precio_mensual,cuota_storage_gb,activo) VALUES($1,20,10,false) RETURNING *',[nombre]);
    return (await pool.query('UPDATE planes SET inactivo_desde=$2 WHERE id=$1 RETURNING *',[plan.id,new Date(+ahora-edad)])).rows[0];
  };
  const leer = async id => (await pool.query('SELECT * FROM planes WHERE id=$1',[id])).rows[0];
  const sinUso = await crear('Nunca utilizado',31*dia);
  const limite = await crear('Exactamente 30 días',30*dia);
  const reciente = await crear('Aún no cumple 30 días',30*dia-1);
  const historico = await crear('Historial con suscripción',31*dia);
  const pagoSolo = await crear('Solo pago antiguo',31*dia);
  const vigente = await crear('Cliente aún vigente',31*dia);
  const pendiente = await crear('Suscripción futura',31*dia);
  const reactivado = await crear('Reactivado a tiempo',31*dia);
  const repo = crearAdminRepositorio(pool), admin = crearCasosAdministracion({ repo });
  const activado = await admin.guardarPlan(actor,reactivado.id,{...reactivado,precio_mensual:20,activo:true});
  assert.equal(activado.inactivo_desde,null);
  await admin.guardarPlan(actor,activado.id,{...activado,precio_mensual:20,activo:false,inactivo_desde:'1900-01-01T00:00:00Z',archivado_en:'1900-01-01T00:00:00Z'});
  assert.ok(+new Date((await leer(reactivado.id)).inactivo_desde)>+instante-dia);
  assert.equal((await leer(reactivado.id)).archivado_en,null);
  await pool.query("INSERT INTO suscripciones(usuario_id,plan_id,fecha_inicio,fecha_fin,estado) VALUES($1,$2,$3,$4,'VENCIDA')",[usuarios[0],historico.id,new Date(+ahora-60*dia),new Date(+ahora-31*dia)]);
  for (const p of [historico,pagoSolo]) await pool.query("INSERT INTO pagos(id,usuario_id,plan_id,plan_nombre,monto,metodo,codigo) VALUES($1,$2,$3,$4,20,'TARJETA',$5)",[randomUUID(),usuarios[0],p.id,p.nombre,randomUUID()]);
  await pool.query("UPDATE suscripciones SET estado='VENCIDA' WHERE usuario_id=$1",[usuarios[1]]);
  await pool.query("INSERT INTO suscripciones(usuario_id,plan_id,fecha_inicio,fecha_fin,estado) VALUES($1,$2,$3,$4,'ACTIVA')",[usuarios[1],vigente.id,new Date(+ahora-dia),new Date(+ahora+dia)]);
  await pool.query("INSERT INTO suscripciones(usuario_id,plan_id,fecha_inicio,fecha_fin,estado) VALUES($1,$2,$3,$4,'PENDIENTE')",[usuarios[2],pendiente.id,new Date(+ahora+dia),new Date(+ahora+40*dia)]);
  const fotos = async () => ({ pagos:(await pool.query('SELECT * FROM pagos ORDER BY id')).rows,suscripciones:(await pool.query('SELECT * FROM suscripciones ORDER BY id')).rows });
  const antes = await fotos();
  const resultados = await Promise.all([limpiarPlanesInactivos(reloj()),limpiarPlanesInactivos(reloj())]);
  assert.equal(resultados.reduce((s,r)=>s+r.eliminados,0),2);
  assert.equal(resultados.reduce((s,r)=>s+r.archivados,0),2);
  assert.equal(await leer(sinUso.id),undefined); assert.equal(await leer(limite.id),undefined);
  assert.ok((await leer(historico.id)).archivado_en); assert.ok((await leer(pagoSolo.id)).archivado_en);
  for (const p of [reciente,vigente,pendiente,reactivado,previo]) assert.equal((await leer(p.id)).archivado_en,null);
  assert.deepEqual(await fotos(),antes);
  const lista = await repo.listarPlanes();
  assert.ok(!lista.some(p=>[sinUso.id,limite.id,historico.id,pagoSolo.id].includes(p.id)));
  assert.ok(lista.some(p=>p.id===vigente.id));
  const log = await admin.listarAuditoria({pagina:'1',q:'Nunca utilizado',accion:'PLAN_ELIMINADO'});
  assert.equal(log.total,1); assert.equal(log.items[0].administrador,'Sistema automático'); assert.equal(log.items[0].detalles_json.nuevo,null);
  assert.equal(log.items[0].detalles_json.anterior.id,sinUso.id);
  const archivado = await leer(historico.id);
  await assert.rejects(admin.guardarPlan(actor,historico.id,{...archivado,precio_mensual:20,activo:true}),{codigo:'PLAN_ARCHIVADO'});
  const pagos = crearCasosPagos({repo:crearPagosRepositorio(pool)});
  assert.equal((await pagos.historial(usuarios[0])).length,2);
  assert.equal((await limpiarPlanesInactivos(reloj())).eliminados,0);
  const {rows:[cuenta]}=await pool.query("SELECT count(*)::int AS n FROM auditoria a JOIN tipos_accion t ON t.id=a.tipo_accion_id WHERE t.codigo IN('PLAN_ARCHIVADO','PLAN_ELIMINADO')");
  assert.equal(cuenta.n,4);
  await assert.rejects(pool.query("UPDATE planes SET activo=false WHERE nombre='Free'"),{code:'23514'});
  assert.equal((await pool.query("SELECT activo FROM planes WHERE nombre='Free'")).rows[0].activo,true);
  // Un fallo al registrar el evento revierte también el borrado definitivo.
  const rollback = await crear('Revertir si falla auditoría',31*dia);
  await assert.rejects(limpiarPlanesInactivos(reloj(true)),/fallo auditoría/);
  assert.ok(await leer(rollback.id));
  // Al finalizar la suscripción se puede retirar el plan, sin tocar su registro histórico.
  ahora = new Date(+instante+2*dia);
  await limpiarPlanesInactivos(reloj());
  assert.ok((await leer(vigente.id)).archivado_en);
  assert.equal((await leer(pendiente.id)).archivado_en,null);
  assert.deepEqual(await fotos(),antes);
  const cuotasRepo = crearCuotasRepositorio(pool);
  const cuotas = crearCasosCuotas({repo:{...cuotasRepo,conUsuario:(id,fn)=>cuotasRepo.conUsuario(id,tx=>{tx.ahora=ahora;return fn(tx);})},almacenamiento:{}});
  assert.equal((await cuotas.consultar(usuarios[1])).plan.nombre,'Free');
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM suscripciones WHERE plan_id=$1',[vigente.id])).rows[0].n,1);
});
